-- Zao backend tables. Data API is locked down: RLS on, no anon/authenticated grants.
-- The Node API uses DATABASE_URL / service_role only.

create table public.users (
  id text primary key,
  email text not null unique,
  name text not null,
  public_key text not null,
  secret_enc text not null,
  kyc_status text not null default 'NEEDS_INFO',
  kyc_id text,
  created_at bigint not null
);

create table public.sessions (
  token text primary key,
  user_id text not null references public.users(id) on delete cascade,
  created_at bigint not null
);

create table public.groups (
  id bigint generated by default as identity primary key,
  onchain_id bigint,
  leader_id text not null references public.users(id),
  member_ids text not null,
  create_tx text,
  created_at bigint not null
);

create table public.loans (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.groups(id) on delete cascade,
  onchain_id bigint,
  principal text not null,
  due_amount text not null,
  status text not null,
  signatures text not null default '[]',
  disbursed_at bigint,
  due_at bigint,
  request_tx text,
  disburse_tx text,
  repay_tx text,
  default_tx text,
  flagged_overdue integer not null default 0,
  created_at bigint not null
);

create table public.escrows (
  id bigint generated by default as identity primary key,
  onchain_id bigint,
  buyer_id text not null references public.users(id),
  seller_id text not null references public.users(id),
  amount text not null,
  status text not null,
  create_tx text,
  fund_tx text,
  close_tx text,
  created_at bigint not null
);

create table public.anchor_txs (
  id text primary key,
  user_id text not null references public.users(id) on delete cascade,
  kind text not null,
  status text not null,
  url text,
  created_at bigint not null
);

create index sessions_user_id_idx on public.sessions (user_id);
create index groups_leader_id_idx on public.groups (leader_id);
create index loans_group_id_idx on public.loans (group_id);
create index loans_overdue_idx on public.loans (status, flagged_overdue, due_at);
create index escrows_buyer_id_idx on public.escrows (buyer_id);
create index anchor_txs_user_id_idx on public.anchor_txs (user_id);

alter table public.users enable row level security;
alter table public.sessions enable row level security;
alter table public.groups enable row level security;
alter table public.loans enable row level security;
alter table public.escrows enable row level security;
alter table public.anchor_txs enable row level security;

revoke all on table public.users from anon, authenticated;
revoke all on table public.sessions from anon, authenticated;
revoke all on table public.groups from anon, authenticated;
revoke all on table public.loans from anon, authenticated;
revoke all on table public.escrows from anon, authenticated;
revoke all on table public.anchor_txs from anon, authenticated;

comment on table public.users is 'Invisible Stellar wallets; secret_enc is AES-GCM ciphertext. Backend-only.';
comment on column public.users.secret_enc is 'Encrypted Stellar secret. Never expose via Data API or logs.';
